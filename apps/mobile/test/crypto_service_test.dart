import 'dart:convert';
import 'package:flutter_test/flutter_test.dart';
import 'package:totp_authenticator/services/crypto_service.dart';

void main() {
  group('CryptoService', () {
    test('generateSalt returns 16 bytes by default', () {
      final salt = CryptoService.generateSalt();
      expect(salt.length, 16);
    });

    test('encrypt and decrypt roundtrip preserves plaintext', () {
      const password = 'SuperSecretMasterPassword!#123';
      final salt = CryptoService.generateSalt();
      const plaintext = '{"accounts":[{"id":"1","name":"Google","secret":"JBSWY3DPEHPK3PXP"}]}';

      final ciphertext = CryptoService.encryptData(plaintext, password, salt);
      expect(ciphertext, isNotEmpty);
      expect(ciphertext.startsWith('gAAAAA'), isTrue); // Standard Fernet version 0x80

      final decrypted = CryptoService.decryptData(ciphertext, password, salt);
      expect(decrypted, equals(plaintext));
    });

    test('decrypt with wrong password throws InvalidPasswordException', () {
      const password = 'CorrectPassword123';
      const wrongPassword = 'WrongPassword456';
      final salt = CryptoService.generateSalt();
      const plaintext = 'my secret data';

      final ciphertext = CryptoService.encryptData(plaintext, password, salt);

      expect(
        () => CryptoService.decryptData(ciphertext, wrongPassword, salt),
        throwsA(isA<InvalidPasswordException>()),
      );
    });

    test('decrypt with corrupted ciphertext throws InvalidPasswordException', () {
      const password = 'Password123';
      final salt = CryptoService.generateSalt();
      const plaintext = 'sample data';

      final ciphertext = CryptoService.encryptData(plaintext, password, salt);
      final corrupted = '${ciphertext.substring(0, ciphertext.length - 8)}AAAA';

      expect(
        () => CryptoService.decryptData(corrupted, password, salt),
        throwsA(isA<InvalidPasswordException>()),
      );
    });

    test('cross-platform compatibility: decrypts token generated by Python desktop client', () {
      const password = 'test_pass_123';
      const saltBase64 = 'cPdFcEnBDg1Ln_oam0uO5w==';
      const tokenFromPython =
          'gAAAAABq7Gnf6jaYJ6UA3jz86CDnwG7LeOiVRQeKnQhljEZXWKK-UfqdRSk0SL9MrF88o_ekd9fpZdM63ZENBVyKBYbos6ExilOLsIW1pCM1PDKhPqZf5WY=';

      // Decode base64url salt
      final normalizedSalt = saltBase64.replaceAll('-', '+').replaceAll('_', '/');
      final salt = base64.decode(normalizedSalt);

      final decrypted = CryptoService.decryptData(tokenFromPython, password, salt);
      expect(decrypted, equals('Hello from Python!'));
    });
  });
}
